import { chromium } from 'playwright-core'
import { mkdir, writeFile } from 'node:fs/promises'

const base = process.env.CPU_URL || 'http://127.0.0.1:5302'
const suffix = base.endsWith('5303') ? '-production' : ''
await mkdir('qa/screens/cpu', { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 810 } })
const checks = [], errors = []
page.on('pageerror', e => errors.push(String(e)))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
const check = (name, ok, details) => { checks.push({ name, ok: !!ok, details }); console.log(`${ok ? 'PASS' : 'FAIL'} ${name} ${JSON.stringify(details ?? '')}`) }
const ready = async name => {
  await page.waitForFunction(name => window.__ipl?.sm.currentName === name && !__ipl.sm._busy, name, { timeout: 30000 })
  await page.locator('#boot').waitFor({ state: 'detached' })
}
const fight = async () => {
  await page.keyboard.press('x')
  await page.waitForFunction(() => window.__scene?.phase === 'fight', null, { timeout: 25000 })
}
const click = action => page.locator(`.session-overlay [data-action="${action}"]`).click()
const shot = name => page.screenshot({ path: `qa/screens/cpu/${name}${suffix}.png` })
const choose = n => page.locator(`.session-overlay input[value="${n}"]`).check()
try {
  await page.goto(`${base}/?scene=hub&mute=1`)
  await ready('hub')
  await page.locator('[data-realm="duel"]').click()
  await page.getByRole('button', { name: 'Single Duel', exact: true }).click()
  await page.locator('.realm-hub input[value="6"]').check()
  await page.getByRole('button', { name: 'Prepare loadout', exact: true }).click()
  await ready('loadout')
  await page.getByRole('button', { name: /ENTER THE CRUCIBLE/ }).click()
  await ready('duel')
  await fight()
  check('forge launch preserves Single Duel and selected CPU', await page.evaluate(() => __scene.mode === 'single' && __scene.ctx.cpuDifficulty.level === 6 && __scene.ai.cfg.level === 6 && __scene.foe.name === 'ASHBORN'))
  check('single-duel play stats separate from Tower', await page.evaluate(() => __ipl.sm.profile.stats.plays.duelSingle === 1 && !__ipl.sm.profile.stats.plays.duel))
  check('single-duel HUD identifies level', await page.locator('.duel-chip').textContent().then(t => t.includes('SINGLE DUEL') && t.includes('CPU 6')))
  const x = await page.evaluate(() => __scene.player.pos.x)
  await page.keyboard.down('ArrowRight'); await page.waitForTimeout(280); await page.keyboard.up('ArrowRight')
  check('arrow movement still works', await page.evaluate(x => __scene.player.pos.x > x + .1, x))
  await page.locator('.session-menu').click()
  const t = await page.evaluate(() => __scene.roundT)
  for (let n = 1; n <= 10; n++) { await choose(n); check(`pause level ${n} selectable`, await page.evaluate(n => __ipl.sm.profile.cpuLevel === n, n)) }
  await page.locator('.session-overlay input[value="10"]').press('ArrowLeft')
  check('pause radio arrows isolated from game', await page.evaluate(() => __ipl.sm.profile.cpuLevel === 9 && __ipl.input.blocked))
  await choose(10)
  check('pending level copy and match snapshot stay accurate', await page.locator('.session-overlay .cpu-note').textContent().then(t => t.includes('stays at level 6') && t.includes('Level 10')) && await page.evaluate(() => __scene.ai.cfg.level === 6 && __scene.ctx.cpuDifficulty.level === 6))
  await page.waitForTimeout(350)
  check('changing CPU level leaves simulation paused', await page.evaluate(t => __scene.roundT === t, t))
  await page.locator('.session-overlay [data-action="resume"]').focus()
  await page.keyboard.press('Shift+Tab')
  check('pause focus wraps backward', await page.evaluate(() => document.activeElement.dataset.action === 'motion'))
  await page.keyboard.press('Tab')
  check('pause focus wraps forward', await page.evaluate(() => document.activeElement.dataset.action === 'resume'))
  await click('sound'); await click('sound')
  await click('motion'); await click('motion')
  for (const value of ['performance', 'high', 'auto']) {
    await page.locator('#session-quality').selectOption(value)
    check(`graphics ${value} still usable with CPU controls`, await page.evaluate(value => __ipl.session.preferences.quality === value, value))
  }
  for (const [width, height] of [[1440, 810], [900, 800], [390, 844]]) {
    await page.setViewportSize({ width, height })
    await shot(`pause-${width}-${height}`)
    check(`pause controls fit width at ${width}x${height}`, await page.locator('.session-panel').evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && el.scrollWidth <= el.clientWidth + 1 }))
    await choose(1); await choose(10)
    await click('motion'); await click('motion')
  }
  await page.setViewportSize({ width: 1440, height: 810 })
  await page.keyboard.press('Escape')
  check('Escape resumes the same CPU match', await page.evaluate(() => !__ipl.session.opened && __scene.ai.cfg.level === 6))
  await page.locator('.session-menu').click()
  await click('resume')
  check('Resume button retains active level', await page.evaluate(() => !__ipl.session.opened && __scene.ai.cfg.level === 6))
  await page.locator('.session-menu').click()
  await click('restart')
  await ready('duel'); await fight()
  check('restart takes pending level and keeps Single Duel', await page.evaluate(() => __scene.mode === 'single' && __scene.ai.cfg.level === 10))
  check('restart clears pending notice and updates CPU badge', await page.locator('.session-cpu-badge').textContent().then(t => t === 'CPU 10'))
  const stats10 = await page.evaluate(() => ({ playerHp: __scene.player.hp, foeHp: __scene.foe.hp, reach: __scene.foe.reachMul(), walk: __scene.foe.walkMul() }))
  check('level 10 starts with ordinary fighter stats', stats10.foeHp === 100 && stats10.reach === 1 && stats10.walk === 1, stats10)
  // Run the real round resolution paths, including a deciding KO finisher.
  await page.evaluate(() => __scene.debug.winRound())
  await page.waitForFunction(() => __scene.phase === 'fight' && __scene.roundIdx === 1, null, { timeout: 14000 })
  check('best of three continues after first round', await page.evaluate(() => __scene.playerWins === 1 && __scene.stage === 0 && !__scene.over))
  await page.evaluate(() => __scene.debug.winRound())
  await page.waitForFunction(() => __scene.phase === 'oblitPrompt')
  await page.keyboard.press('j')
  await page.waitForFunction(() => __scene.over === 'won', null, { timeout: 14000 })
  check('deciding KO ends Single Duel without advancing Tower', await page.evaluate(() => __scene.stage === 0 && __scene.playerWins === 2 && __ipl.sm.profile.stats.wins.duelSingle === 1 && !__ipl.sm.profile.stats.wins.duel))
  await shot('single-victory')
  for (const [width, height] of [[1440, 810], [900, 800], [390, 844]]) {
    await page.setViewportSize({ width, height })
    await shot(`result-${width}-${height}`)
    const rects = await page.locator('.duel-panel, .duel-panel button').evaluateAll(els => els.map(el => { const r = el.getBoundingClientRect(); return { text: el.textContent.slice(0, 50), x: r.x, y: r.y, right: r.right, bottom: r.bottom, w: innerWidth, h: innerHeight } }))
    check(`result panel and both actions fit at ${width}x${height}`, rects.every(r => r.x >= 0 && r.y >= 0 && r.right <= r.w && r.bottom <= r.h), rects)
  }
  await page.getByRole('button', { name: 'REMATCH', exact: true }).click()
  await ready('duel'); await fight()
  check('mobile rematch starts Single Duel at current level', await page.evaluate(() => __scene.ai.cfg.level === 10 && __scene.mode === 'single' && __scene.playerWins === 0))
  await page.setViewportSize({ width: 1440, height: 810 })
  for (let round = 0; round < 2; round++) {
    await page.evaluate(() => { __scene.player.hp = 0; __scene._endRound(__scene.foe, true) })
    await page.waitForFunction(round => round ? __scene.over === 'lost' : __scene.phase === 'fight' && __scene.roundIdx === 1, round, { timeout: 14000 })
  }
  check('loss ends best-of-three without a Tower loss or victory', await page.evaluate(() => __scene.foeWins === 2 && __scene.stage === 0 && __ipl.sm.profile.stats.wins.duelSingle === 1 && !__ipl.sm.profile.stats.wins.duel))
  await shot('single-defeat')
  await page.getByRole('button', { name: 'CHOOSE BATTLEGROUND', exact: true }).click()
  await ready('hub')
  check('single result returns to hub with separate record', await page.locator('.realm-record').textContent().then(t => t.includes('1 victory in Single Duel')))
  await page.getByRole('button', { name: 'Tower', exact: true }).click()
  await page.getByRole('button', { name: 'ENTER BATTLE', exact: true }).click()
  await ready('duel'); await fight()
  check('Tower ignores saved level 10', await page.evaluate(() => __scene.mode === 'tower' && __scene.ctx.cpuDifficulty === null && __scene.ai.cfg.reaction === .42 && __scene.ai.cfg.blockProb === .25 && __scene.ai.cfg.level == null))
  await page.locator('.session-menu').click()
  check('Tower pause has no level picker or badge', !await page.locator('.session-overlay .cpu-difficulty').isVisible() && !await page.locator('.session-cpu-badge').isVisible())
  await click('hub'); await ready('hub')
  await page.locator('[data-realm="brawl"]').click()
  await page.locator('.realm-hub input[value="1"]').check()
  await page.getByRole('button', { name: 'ENTER BATTLE', exact: true }).click()
  await ready('brawl'); await fight()
  check('Brawl all opponents receive level 1', await page.evaluate(() => __scene.ais.length === 2 && __scene.ais.every(a => a.difficulty.level === 1)))
  await page.waitForTimeout(1700)
  check('Brawl CPUs move and fight', await page.evaluate(() => __scene.ais.some(a => Math.abs(a.f.vel.x) > .1 || a.f.attack || a.f.dmg > 0)))
  await page.locator('.session-menu').click(); await choose(10)
  check('Brawl pause keeps level 1 active', await page.evaluate(() => __scene.ais.every(a => a.difficulty.level === 1)))
  await click('restart'); await ready('brawl'); await fight()
  check('Brawl restart takes level 10 for both opponents', await page.evaluate(() => __scene.ais.every(a => a.difficulty.level === 10)))
  // Invoke the actual existing summon caster without altering the saved loadout.
  await page.evaluate(() => __scene._casters.summon({ color: '#ffe0ad', params: { hp: 24, duration: 6 } }))
  check('Phantom Twin ally stays fixed at level 5', await page.evaluate(() => __scene.clone.ai.difficulty.level === 5 && __scene.clone.ai.jabsOnly))
  await shot('brawl-level10')
  await page.locator('.session-menu').click(); await click('hub'); await ready('hub')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  check('hub settings omit match CPU picker', !await page.locator('.session-overlay .cpu-difficulty').isVisible())
  await page.keyboard.press('Escape')
  // Direct-link precedence is separate from the remembered hub mode.
  await page.goto(`${base}/?scene=duel&mode=single&mute=1`); await ready('duel')
  check('single direct link overrides saved Tower mode', await page.evaluate(() => __scene.mode === 'single' && __scene.ctx.cpuDifficulty.level === 10))
  await page.goto(`${base}/?scene=duel&mode=invalid&mute=1`); await ready('duel')
  check('invalid direct mode safely resolves to Tower', await page.evaluate(() => __scene.mode === 'tower' && __scene.ctx.cpuDifficulty === null))
} catch (error) {
  check('probe completed', false, String(error))
  await shot('match-failure').catch(() => {})
} finally {
  check('no runtime browser errors', errors.length === 0, errors)
  await writeFile(`docs/cpu-match-results${suffix}.json`, JSON.stringify({ base, time: new Date().toISOString(), checks, errors }, null, 2) + '\n')
  await browser.close()
}
process.exitCode = checks.some(c => !c.ok) ? 1 : 0
